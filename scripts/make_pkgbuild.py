#!/usr/bin/env python3
"""Generate one PKGBUILD per tool into packaging/arch/<tool>/.

Reads index.json (the generated catalog) and writes a source PKGBUILD for
every tool: fetch the release-tag tarball, build that one crate out of the
workspace with cargo --frozen (the committed Cargo.lock is authoritative),
install the binary. adbkit is skipped — it is a library, not a binary.

The tag tarball's checksum cannot be known before the tag exists, so run
this *after* pushing the release tag:

    python3 scripts/make_pkgbuild.py

Usage: python3 scripts/make_pkgbuild.py
"""

import hashlib
import json
import os
import sys
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARCH_ROOT = os.path.join(ROOT, "packaging", "arch")
REPO = "YoannDev90/android-tools"
MAINTAINER = "YoannDev90 <yoanndev@outlook.fr>"

# Every crate depends on the same workspace, so a tool needs adb exactly when
# it links the adbkit crate (adbkit's own requirement is "adb in PATH").
ADB_DEPENDENT = "adbkit"

PKGBUILD = """# Maintainer: @MAINTAINER@
#
# Generated by scripts/make_pkgbuild.py — do not edit by hand.
# Regenerate once the release tag is pushed: python3 scripts/make_pkgbuild.py

pkgname=@PKGNAME@
pkgver=@PKGVER@
pkgrel=1
pkgdesc=@PKGDESC@
arch=('x86_64' 'aarch64')
url='https://github.com/@REPO@'
license=('MIT')
# makepkg's default `lto` option appends -flto=auto to CFLAGS. Useless here
# (Rust's LTO comes from the cargo profile) and fatal for crates with C code
# such as ring: rust-lld cannot read GCC LTO bitcode, symbols go missing.
options=(!lto)
@DEPENDS@makedepends=('rust')
source=("$pkgname-$pkgver.tar.gz::https://github.com/@REPO@/archive/refs/tags/v$pkgver.tar.gz")
sha256sums=('@SHA256@')

# The tarball is the whole workspace: path dependencies (adbkit, svg2vd) live
# in sibling directories, so cargo runs from the workspace root and builds
# only this package's dependency tree.
prepare() {
  cd "$srcdir/@REPO_NAME@-$pkgver"
  cargo fetch --locked
}

build() {
  cd "$srcdir/@REPO_NAME@-$pkgver"
  cargo build --frozen --release -p "$pkgname"
}

check() {
  cd "$srcdir/@REPO_NAME@-$pkgver"
  cargo test --frozen -p "$pkgname"
}

package() {
  cd "$srcdir/@REPO_NAME@-$pkgver"
  install -Dm755 "target/release/$pkgname" "$pkgdir/usr/bin/$pkgname"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 "$pkgname/README.md" "$pkgdir/usr/share/doc/$pkgname/README.md"
}
"""


def sh(value):
    """Single-quote a value for bash."""
    return "'" + str(value).replace("'", "'\\''") + "'"


def tag_sha256(version):
    """sha256 of the GitHub auto-generated tarball for the given tag."""
    url = "https://github.com/{}/archive/refs/tags/v{}.tar.gz".format(REPO, version)
    try:
        with urllib.request.urlopen(url, timeout=60) as resp:
            data = resp.read()
    except (urllib.error.URLError, OSError) as exc:
        sys.exit(
            "error: cannot fetch {}\n"
            "       ({})\n"
            "       the v{} tag must be pushed first — re-run "
            "scripts/make_pkgbuild.py afterwards.".format(url, exc, version)
        )
    return hashlib.sha256(data).hexdigest()


def render(tool, version, sha256):
    depends = ""
    if ADB_DEPENDENT in tool.get("dependencies", {}):
        # adb is the external program these tools shell out to.
        depends = "depends=('android-tools')\n"
    return (
        PKGBUILD.replace("@MAINTAINER@", MAINTAINER)
        .replace("@PKGNAME@", tool["name"])
        .replace("@PKGVER@", version)
        .replace("@PKGDESC@", sh(tool["description"]))
        .replace("@REPO@", REPO)
        .replace("@REPO_NAME@", REPO.split("/")[1])
        .replace("@DEPENDS@", depends)
        .replace("@SHA256@", sha256)
    )


def main():
    with open(os.path.join(ROOT, "index.json"), encoding="utf-8") as f:
        tools = json.load(f)["tools"]

    tools = [t for t in tools if t["category"] != "library"]
    if not tools:
        sys.exit("error: no tools found in index.json")

    versions = {t["version"] for t in tools}
    if len(versions) != 1:
        sys.exit("error: tools do not share one version: {}".format(sorted(versions)))
    version = versions.pop()

    sha256 = tag_sha256(version)

    written = []
    for tool in tools:
        out_dir = os.path.join(ARCH_ROOT, tool["name"])
        os.makedirs(out_dir, exist_ok=True)
        path = os.path.join(out_dir, "PKGBUILD")
        with open(path, "w", encoding="utf-8") as f:
            f.write(render(tool, version, sha256))
        written.append(tool["name"])

    # A tool removed from the catalog leaves its directory behind.
    stale = sorted(
        d for d in os.listdir(ARCH_ROOT)
        if os.path.isfile(os.path.join(ARCH_ROOT, d, "PKGBUILD")) and d not in written
    )
    if stale:
        print("warning: stale PKGBUILD dirs (remove if the tools are gone): "
              + ", ".join(stale))

    print("wrote {} PKGBUILDs to packaging/arch/ (pkgver {}, sha256 {}): {}".format(
        len(written), version, sha256[:12], ", ".join(written)))


if __name__ == "__main__":
    main()
